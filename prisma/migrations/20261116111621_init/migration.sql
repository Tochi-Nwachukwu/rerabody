-- Hand-edited: keep Product."searchVector" current with a trigger.
-- Name is weighted A, the text nodes of the Tiptap description JSON are weighted B.
-- A trigger is used instead of a generated column so Prisma Migrate reports no drift.
CREATE FUNCTION product_search_vector_update() RETURNS trigger AS $$
BEGIN
  NEW."searchVector" :=
    setweight(to_tsvector('english'::regconfig, coalesce(NEW."name", '')), 'A') ||
    setweight(to_tsvector('english'::regconfig,
      coalesce(jsonb_path_query_array(NEW."description", 'strict $.**.text')::text, '')), 'B');
  RETURN NEW;
END
$$ LANGUAGE plpgsql;

CREATE TRIGGER "Product_searchVector_trigger"
  BEFORE INSERT OR UPDATE OF "name", "description" ON "Product"
  FOR EACH ROW EXECUTE FUNCTION product_search_vector_update();
